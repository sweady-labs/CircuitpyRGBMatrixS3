_cache = {}


def glyph(char, table=None):
    """(width, ((x, y), ...)) for a character; unknown characters become "?"."""
    if table is None:
        table = NORMAL
    key = (id(table), char)
    found = _cache.get(key)
    if found:
        return found
    data = table.get(char)
    if data is None:
        data = table.get(ALIASES.get(char, "?")) or table.get("?") or table[" "]
    rows = data.split("|")
    pixels = tuple((x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#")
    found = (len(rows[0]), pixels)
    _cache[key] = found
    return found
